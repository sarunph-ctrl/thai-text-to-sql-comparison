-- Five-table synthetic sales + inventory demo. Original sales tables retained.
CREATE TABLE IF NOT EXISTS products (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    price NUMERIC(12,2) NOT NULL CHECK (price >= 0)
);
CREATE TABLE IF NOT EXISTS orders (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_date DATE NOT NULL,
    status TEXT NOT NULL CHECK (status IN ('paid', 'pending', 'cancelled'))
);
CREATE TABLE IF NOT EXISTS order_items (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id INTEGER NOT NULL REFERENCES orders(id),
    product_id INTEGER NOT NULL REFERENCES products(id),
    qty INTEGER NOT NULL CHECK (qty > 0),
    unit_price NUMERIC(12,2) NOT NULL CHECK (unit_price >= 0)
);

CREATE TABLE IF NOT EXISTS warehouses (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE
);

-- Composite key lets a linked issue enforce the SAME product as its sales line.
CREATE UNIQUE INDEX IF NOT EXISTS demo_order_items_id_product_key
    ON order_items(id, product_id);

CREATE TABLE IF NOT EXISTS stock_movements (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id INTEGER NOT NULL REFERENCES products(id),
    warehouse_id INTEGER NOT NULL REFERENCES warehouses(id),
    movement_date DATE NOT NULL,
    movement_type TEXT NOT NULL CHECK (movement_type IN ('opening', 'receipt', 'issue')),
    qty INTEGER NOT NULL CHECK (qty > 0),
    order_item_id INTEGER,
    CHECK (order_item_id IS NULL OR movement_type = 'issue'),
    FOREIGN KEY (order_item_id, product_id) REFERENCES order_items(id, product_id)
);

-- One opening balance per product/warehouse. All changes afterwards are events.
CREATE UNIQUE INDEX IF NOT EXISTS demo_one_opening_balance
    ON stock_movements(warehouse_id, product_id) WHERE movement_type = 'opening';
CREATE INDEX IF NOT EXISTS demo_stock_balance_lookup
    ON stock_movements(warehouse_id, product_id);
CREATE INDEX IF NOT EXISTS demo_stock_period_lookup
    ON stock_movements(movement_type, movement_date);
